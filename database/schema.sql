-- NEXO TRIO | PostgreSQL 15+
-- O instalador executa este arquivo uma única vez no banco do Render.

CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(6) NOT NULL UNIQUE,
    host_player_id BIGINT NULL,
    module_count SMALLINT NOT NULL CHECK (module_count BETWEEN 2 AND 4),
    duration_seconds SMALLINT NOT NULL DEFAULT 480 CHECK (duration_seconds > 0),
    status VARCHAR(12) NOT NULL DEFAULT 'lobby' CHECK (status IN ('lobby','active','won','failed')),
    started_at BIGINT NULL,
    errors SMALLINT NOT NULL DEFAULT 0 CHECK (errors >= 0),
    game_json TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rooms_status ON rooms(status);

CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    player_name VARCHAR(32) NOT NULL,
    role VARCHAR(8) NOT NULL CHECK (role IN ('surdo','cego','mudo')),
    is_host SMALLINT NOT NULL DEFAULT 0 CHECK (is_host IN (0,1)),
    ready SMALLINT NOT NULL DEFAULT 0 CHECK (ready IN (0,1)),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_room_role UNIQUE (room_id, role)
);

CREATE INDEX IF NOT EXISTS idx_players_room ON players(room_id);

-- O conteúdo serializado da sessão é armazenado em Base64 para preservar bytes nulos.
CREATE TABLE IF NOT EXISTS nexo_sessions (
    session_id VARCHAR(128) PRIMARY KEY,
    session_data TEXT NOT NULL,
    last_activity BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_nexo_sessions_activity ON nexo_sessions(last_activity);
